def who(route) -> str:
    """Read the role rule straight from the route's dependencies."""
    for dep in route.dependant.dependencies:
        fn = dep.call
        if getattr(fn, "__name__", "") == "checker" and fn.__closure__:
            roles = next((c.cell_contents for c in fn.__closure__ if isinstance(c.cell_contents, tuple)), ())
            return ", ".join(r.value.replace("_", " ") for r in roles)
        if getattr(fn, "__name__", "") == "get_current_user":
            return "any signed-in user"
    return "anyone"


def flat(routes):
    """Newer FastAPI versions wrap each included router; older ones list the routes directly."""
    for r in routes:
        inner = getattr(r, "original_router", None)
        if inner is not None:
            yield from flat(inner.routes)
        else:
            yield r


