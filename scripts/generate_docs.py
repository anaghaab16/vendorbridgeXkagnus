rows = []
for r in flat(app.routes):
    if not hasattr(r, "methods") or not hasattr(r, "dependant") or r.path in ("/openapi.json", "/docs", "/docs/oauth2-redirect", "/redoc"):
        continue
    for m in sorted(r.methods - {"HEAD", "OPTIONS"}):
        rows.append((r.tags[0] if r.tags else "other", r.path, m, who(r), PLAIN.get((m, r.path), (r.summary or r.name).replace("_", " "))))
rows.sort(key=lambda x: (x[0], x[1], x[2]))

lines = ["# API reference", "",
         "Generated by `python scripts/generate_docs.py` from the code. Interactive version: `/docs` on the running backend.", "",
         "Send the login token as `Authorization: Bearer <token>`. Errors come back as `{\"detail\": \"...\"}`; "
         "validation errors (422) list each field. Common codes: 401 not signed in, 403 role not allowed, 404 not found "
         "or not yours, 409 clashes with the current state (duplicates, wrong status), 422 invalid data.", ""]
tag = None
for t, path, method, roles, summary in rows:
    if t != tag:
        tag = t
        lines += ["", f"## {t}", "", "| Method | Path | Who may call it | What it does |", "|---|---|---|---|"]
    lines.append(f"| {method} | `{path}` | {roles} | {summary} |")
lines.append("")
(out / "API.md").write_text("\n".join(lines), encoding="utf-8")

db = ["# Database structure", "",
      "Generated by `python scripts/generate_docs.py` from the SQLAlchemy models. PostgreSQL in production; tables are created on startup.", ""]
for table in app.database.Base.metadata.sorted_tables:
    db += ["", f"## `{table.name}`", "", "| Column | Type | Null | Notes |", "|---|---|---|---|"]
    for c in table.columns:
        notes = []
        if c.primary_key:
            notes.append("primary key")
        if c.unique:
            notes.append("unique")
        for fk in c.foreign_keys:
            notes.append(f"-> `{fk.target_fullname}`")
        if c.default is not None and getattr(c.default, "arg", None) is not None and not callable(c.default.arg):
            notes.append(f"default {c.default.arg}")
        db.append(f"| {c.name} | {str(c.type).replace('|', '/')} | {'yes' if c.nullable else 'no'} | {'; '.join(notes)} |")
    extra = []
    for con in table.constraints:
        if con.__class__.__name__ == "UniqueConstraint" and len(con.columns) > 1:
            extra.append(f"unique together: {', '.join(c.name for c in con.columns)}")
        if con.__class__.__name__ == "ForeignKeyConstraint" and len(con.columns) > 1:
            extra.append(f"composite foreign key: ({', '.join(c.name for c in con.columns)}) -> `{con.elements[0].column.table.name}`")
    for ix in table.indexes:
        if ix.unique and len(ix.columns) == 1 and ix.dialect_options["postgresql"].get("where") is not None:
            extra.append(f"partial unique index `{ix.name}` on {next(iter(ix.columns)).name}")
    if table.name == "audit_logs":
        extra.append("write-once: the application never updates or deletes rows, and on PostgreSQL triggers refuse it too")
    if extra:
        db += ["", *[f"- {e}" for e in extra]]
db.append("")
(out / "DATABASE.md").write_text("\n".join(db), encoding="utf-8")
print(f"wrote {out / 'API.md'} ({len(rows)} endpoints) and {out / 'DATABASE.md'} ({len(app.database.Base.metadata.sorted_tables)} tables)")